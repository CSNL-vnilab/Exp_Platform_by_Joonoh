#!/usr/bin/env node
// Regenerate the curated payment-PDF subset font + its coverage table.
//
// The 연구참여비 지급신청서 PDF (template-filler.ts) embeds a Korean font
// per-participant. Full NanumGothic (2 MB) full-embedded makes a 10-person
// claim email exceed Gmail's 25 MB cap. This script pre-subsets the font
// to ASCII + KS X 1001 hangul (2,350 syllables) + common symbols (~743 KB),
// which we then full-embed (subset:false) at runtime — avoiding pdf-lib's
// runtime subsetter, which dropped glyphs in the 2026-06-10 "글씨 누락" bug.
//
// Outputs (committed to the repo):
//   src/lib/payments/templates/fonts/NanumGothic-payment.ttf
//   src/lib/payments/payment-font-coverage.ts   (runtime curated-vs-full gate)
//
// Requires: python3 with fonttools (`pip install fonttools`) → pyftsubset.
// Run:  node scripts/build-payment-font.mjs
//
// The full NanumGothic-Regular.ttf stays in the repo as the fallback embed
// for names/titles carrying a glyph outside KS X 1001.

import { execFileSync } from "node:child_process";
import { writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const FONTS = path.join(ROOT, "src/lib/payments/templates/fonts");
const SRC_FONT = path.join(FONTS, "NanumGothic-Regular.ttf");
const OUT_FONT = path.join(FONTS, "NanumGothic-payment.ttf");
const OUT_COVERAGE = path.join(ROOT, "src/lib/payments/payment-font-coverage.ts");

// Compute the codepoint set in Python (EUC-KR enumeration for KS X 1001)
// and dump it as JSON so this script stays the single source of truth.
const PY = `
import json, sys
cps = set()
for c in range(0x20, 0x7F): cps.add(c)          # ASCII
for ch in "·×∼~…‧∙・": cps.add(ord(ch))
for ch in "～·（）「」〜／：－．，　": cps.add(ord(ch))
for lead in range(0xB0, 0xC9):                   # KS X 1001 hangul rows
    for tail in range(0xA1, 0xFF):
        try: ch = bytes([lead, tail]).decode('euc-kr')
        except Exception: continue
        if 0xAC00 <= ord(ch) <= 0xD7A3: cps.add(ord(ch))
json.dump(sorted(cps), sys.stdout)
`;

const coverageJson = execFileSync("python3", ["-c", PY], { encoding: "utf8" });
const cps = JSON.parse(coverageJson);
console.log(`codepoints: ${cps.length}`);

const tmp = mkdtempSync(path.join(tmpdir(), "payfont-"));
const unicodesFile = path.join(tmp, "unicodes.txt");
writeFileSync(
  unicodesFile,
  cps.map((c) => "U+" + c.toString(16).toUpperCase().padStart(4, "0")).join(","),
);

execFileSync(
  "pyftsubset",
  [
    SRC_FONT,
    `--unicodes-file=${unicodesFile}`,
    `--output-file=${OUT_FONT}`,
    "--layout-features=*",
    "--glyph-names",
    "--no-hinting",
    "--desubroutinize",
  ],
  { stdio: "inherit" },
);
console.log(`wrote ${OUT_FONT}`);

// Coverage MUST reflect the OUTPUT font's real cmap, not the requested set:
// the source font may lack some requested symbols, which pyftsubset silently
// drops. Reading the built font's cmap keeps isCoveredByPaymentFont truthful
// (a codepoint we claim is covered but the font can't render would defeat the
// full-font fallback and render blank).
const cmapJson = execFileSync(
  "python3",
  [
    "-c",
    `import json,sys
from fontTools.ttLib import TTFont
f=TTFont(sys.argv[1])
json.dump(sorted(f.getBestCmap().keys()), sys.stdout)`,
    OUT_FONT,
  ],
  { encoding: "utf8" },
);
const covered = JSON.parse(cmapJson);
console.log(`covered (actual cmap): ${covered.length}`);

const ts =
  `// AUTO-GENERATED by scripts/build-payment-font.mjs — do not edit by hand.\n` +
  `// Codepoints ACTUALLY present in NanumGothic-payment.ttf's cmap (ASCII +\n` +
  `// KS X 1001 hangul + whatever symbols the source font contains). Runtime\n` +
  `// uses this to decide whether the curated subset font (subset:false, ~743KB)\n` +
  `// can render a given PDF's text, or whether it must fall back to the full\n` +
  `// NanumGothic (~2MB) for a name/title containing a glyph outside this set.\n` +
  `const COVERED: ReadonlySet<number> = new Set([${covered.join(",")}]);\n\n` +
  `/** True when every codepoint in \`text\` is renderable by the curated\n` +
  ` *  payment subset font. */\n` +
  `export function isCoveredByPaymentFont(text: string): boolean {\n` +
  `  for (const ch of text) {\n` +
  `    const cp = ch.codePointAt(0);\n` +
  `    if (cp === undefined) continue;\n` +
  `    if (!COVERED.has(cp)) return false;\n` +
  `  }\n` +
  `  return true;\n` +
  `}\n`;
writeFileSync(OUT_COVERAGE, ts);
console.log(`wrote ${OUT_COVERAGE}`);
